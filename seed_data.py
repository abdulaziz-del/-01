with app.app_context():
    admin = User.query.filter_by(username='admin').first()
    if not admin:
        print("❌ لا يوجد حساب admin - شغّل init_db أولاً")
        sys.exit(1)

    added_r = added_j = added_p = 0

    for r in REGULATIONS:
        if not Regulation.query.filter_by(title=r['title']).first():
            reg = Regulation(created_by=admin.id, status='published', **r)
            db.session.add(reg)
            added_r += 1

    for j in JUDGMENTS:
        if not Judgment.query.filter_by(title=j['title']).first():
            jud = Judgment(created_by=admin.id, status='published',
                          subject=j.get('subject',''), tags='[]', **{k:v for k,v in j.items() if k != 'subject'})
            db.session.add(jud)
            added_j += 1

    for p in PRINCIPLES:
        if not Principle.query.filter_by(text=p['text']).first():
            pr = Principle(created_by=admin.id, status='published', **p)
            db.session.add(pr)
            added_p += 1

    db.session.commit()
    print(f"✅ تمت إضافة:")
    print(f"   - {added_r} نظام ولائحة")
    print(f"   - {added_j} حكم قضائي")
    print(f"   - {added_p} مبدأ قضائي")
    print(f"   المجموع: {added_r + added_j + added_p} سجل")
